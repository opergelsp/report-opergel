export function traduzir(lang, key, vars) {
  const base = DICIONARIO[lang] || DICIONARIO.pt
  let texto = base[key] != null ? base[key] : (DICIONARIO.pt[key] != null ? DICIONARIO.pt[key] : key)
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      texto = texto.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v))
    })
  }
  return texto
}

export function Bandeiras({ lang, setLang, className }) {
  return (
    <div className={className}>
      {LINGUAS.map((l) => (
        <button
          key={l.id}
          className={'bandeira-btn' + (lang === l.id ? ' ativo' : '')}
          onClick={() => setLang(l.id)}
          title={l.nome}
          aria-label={l.nome}
          aria-pressed={lang === l.id}
        >
          <img src={BANDEIRAS[l.id]} alt={l.nome} />
        </button>
      ))}
    </div>
  )
}